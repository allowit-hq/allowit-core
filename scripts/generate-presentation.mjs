import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('typescript/canonical-functions.json', root), 'utf8');
const registry = JSON.parse(source);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const cargo = await readFile(new URL('Cargo.toml', root), 'utf8');
const workspaceVersion = cargo.match(/\[workspace\.package\][\s\S]*?\nversion\s*=\s*"([^"]+)"/)?.[1];
if (registry.coreVersion !== manifest.version || registry.coreVersion !== workspaceVersion) {
  throw new Error('Rust, npm and function metadata must use the same Core version');
}
const hash = createHash('sha256').update(source, 'utf8').digest('hex');
const names = registry.functions.map(({ name }) => JSON.stringify(name)).join(' | ');
const semantics = [...new Set(registry.functions.map(({ parameter }) => parameter.semanticType))]
  .map(value => JSON.stringify(value)).join(' | ');
const javascript = `// Generated by scripts/generate-presentation.mjs.\n` +
  `export const canonicalFunctionsSource = ${JSON.stringify(source)};\n` +
  `export const canonicalFunctionMetadataHash = ${JSON.stringify(hash)};\n` +
  `function freeze(value) { if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); } return value; }\n` +
  `export const canonicalFunctionRegistry = freeze(JSON.parse(canonicalFunctionsSource));\n` +
  `export const canonicalFunctions = canonicalFunctionRegistry.functions;\n`;
const declarations = `// Generated by scripts/generate-presentation.mjs.\n` + `
/** Canonical signed i128 decimal text. The Rust wire decoder validates its form and range. */
export type IntegerText = string;

interface PolicyValueTypes {
  readonly Int: IntegerText;
  readonly Bool: boolean;
  readonly Str: string;
  /** Opaque identity text. Native adapters validate its address format. */
  readonly Addr: string;
  readonly List: readonly PolicyValue[];
}
export type PolicyValueKind = keyof PolicyValueTypes;
type ValueVariant<K extends PolicyValueKind> = {
  readonly [P in K]: PolicyValueTypes[P];
} & { readonly [P in Exclude<PolicyValueKind, K>]?: never };
/** Exactly one storage tag. Storage tags do not select a user-facing control. */
export type PolicyValue = { [K in PolicyValueKind]: ValueVariant<K> }[PolicyValueKind];
export type PolicyValues = Readonly<Record<string, PolicyValue>>;

export type CanonicalFunctionName = ${names};
export type ParameterSemanticType = ${semantics};
export interface IntegerRange {
  readonly min: IntegerText;
  readonly max: IntegerText;
}
export interface ParameterDescriptor {
  /** Zero-based index of the canonical rule's value argument. */
  readonly index: 1;
  readonly semanticType: ParameterSemanticType;
  readonly storageTypes: readonly PolicyValueKind[];
  readonly itemType: PolicyValueKind | null;
  readonly integerRange: IntegerRange | null;
  /** Units must come from verified host/native context, without an assumed asset or scale. */
  readonly requiresAmountContext: boolean;
  readonly timeUnit?: 'unix_seconds';
  readonly wildcard?: '*';
}
export interface ResultDescriptor {
  readonly kind: 'integer' | 'address' | 'operation';
  readonly description: string;
}
export interface CanonicalFunctionDescriptor {
  readonly name: CanonicalFunctionName;
  readonly path: \`allowit::\${CanonicalFunctionName}\`;
  readonly label: string;
  readonly description: string;
  readonly parameter: ParameterDescriptor;
  readonly result: ResultDescriptor;
}
export interface CanonicalFunctionRegistry {
  readonly schemaVersion: 1;
  readonly coreVersion: string;
  readonly integerRange: IntegerRange;
  readonly functions: readonly CanonicalFunctionDescriptor[];
}
/** Exact UTF-8 input whose SHA-256 identifies the matching metadata. */
export declare const canonicalFunctionsSource: string;
export declare const canonicalFunctionMetadataHash: string;
export declare const canonicalFunctionRegistry: CanonicalFunctionRegistry;
/** Registry order is not authored source or workflow order. */
export declare const canonicalFunctions: readonly CanonicalFunctionDescriptor[];
`;
for (const [path, output] of [['typescript/core.js', javascript], ['typescript/core.d.ts', declarations]]) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error(`${path} differs from its registry input`);
  } else {
    await writeFile(target, output);
  }
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} Core ${workspaceVersion} presentation exports`);
